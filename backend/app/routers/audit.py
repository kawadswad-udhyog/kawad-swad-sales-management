from typing import List, Optional
from fastapi import APIRouter, Depends, Query, HTTPException
from app.models import AuditLogItem
from app.sheets import db
from app.auth import get_current_user
from app.permissions import require_roles

router = APIRouter(prefix="/api/audit-logs", tags=["Audit Log"])


@router.get("", response_model=List[AuditLogItem])
async def list_audit_logs(
    limit: int = Query(250, ge=1, le=1000),
    entity_type: Optional[str] = None,
    current_user: dict = Depends(get_current_user),
):
    # Audit history may contain sensitive employee and financial metadata;
    # strictly restricted to OWNER_ADMIN and read-only AUDITOR (PA and other roles denied).
    require_roles(
        current_user,
        {"OWNER_ADMIN", "AUDITOR"},
        detail="Audit log access requires Owner or Auditor privileges.",
    )
    records = db.get_records("AuditLog")
    items: List[AuditLogItem] = []
    for r in records:
        if entity_type and str(r.get("entity_type", "")).upper() != entity_type.upper():
            continue
        items.append(AuditLogItem(
            audit_id=str(r.get("audit_id", "")),
            event_datetime=str(r.get("event_datetime", "")),
            actor_user_id=str(r.get("actor_user_id", "")),
            action=str(r.get("action", "")),
            entity_type=str(r.get("entity_type", "")),
            entity_id=str(r.get("entity_id", "")),
            field_changed=str(r.get("field_changed", "")),
            old_value=str(r.get("old_value", "")),
            new_value=str(r.get("new_value", "")),
            reason=str(r.get("reason", "")),
            approved_by_user_id=str(r.get("approved_by_user_id", "")),
            related_record_id=str(r.get("related_record_id", "")),
        ))
    items.reverse()
    return items[:limit]


@router.post("", status_code=410)
async def create_audit_log(current_user: dict = Depends(get_current_user)):
    # Client-authored audit events are forgeable. Trusted backend workflows must
    # write audit events through db.log_audit after validating the business action.
    raise HTTPException(
        status_code=410,
        detail="Client-authored audit events are disabled. Audit events are generated by trusted backend workflows.",
    )
