"""
Kawad Swad ERP — Strict Centralized Governed Action-to-Table Allowlist & Read-Back Registry.

Enforces Blueprint v2.1 & ZIP (35) Static Acceptance Audit rules:
1. Strict 1:1 action -> target_tab + id_field contract.
2. Explicit allowlist of cache-invalidation tabs per action (never unregistered tabs).
3. Explicit transaction-specific read-back contracts (primary row, state assertions, child tabs, journal balance).
"""

from dataclasses import dataclass
from typing import Any, Dict, FrozenSet, Optional, Tuple


@dataclass(frozen=True)
class ChildTabCheck:
    tab: str
    fk_field: str
    source_id_key: str  # "allocated_id" or key inside payload/record
    min_rows_payload_key: Optional[str] = None
    condition_payload_key: Optional[str] = None
    verify_journal_balance: bool = False


@dataclass(frozen=True)
class ReadBackSpec:
    primary_match_fields: Tuple[str, ...] = ()
    state_assertions: Tuple[Tuple[str, str], ...] = ()
    child_checks: Tuple[ChildTabCheck, ...] = ()
    expect_absent: bool = False
    expect_absent_or_soft_deleted: bool = False


@dataclass(frozen=True)
class GovernedActionSpec:
    action: str
    target_tab: str
    id_field: Optional[str]
    allowed_invalidate_tabs: FrozenSet[str]
    requires_allocated_id: bool = True
    locked_prefix: Optional[str] = None
    readback: ReadBackSpec = ReadBackSpec()


def _spec(
    action: str,
    target_tab: str,
    id_field: Optional[str],
    invalidate_tabs: Tuple[str, ...],
    *,
    requires_allocated_id: bool = True,
    locked_prefix: Optional[str] = None,
    primary_match_fields: Tuple[str, ...] = (),
    state_assertions: Tuple[Tuple[str, str], ...] = (),
    child_checks: Tuple[ChildTabCheck, ...] = (),
    expect_absent: bool = False,
    expect_absent_or_soft_deleted: bool = False,
) -> GovernedActionSpec:
    inv = frozenset({target_tab, *invalidate_tabs})
    return GovernedActionSpec(
        action=action,
        target_tab=target_tab,
        id_field=id_field,
        allowed_invalidate_tabs=inv,
        requires_allocated_id=requires_allocated_id,
        locked_prefix=locked_prefix,
        readback=ReadBackSpec(
            primary_match_fields=primary_match_fields,
            state_assertions=state_assertions,
            child_checks=child_checks,
            expect_absent=expect_absent,
            expect_absent_or_soft_deleted=expect_absent_or_soft_deleted,
        ),
    )


