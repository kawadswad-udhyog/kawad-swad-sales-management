function ksP1InstallFoundation() {
  const lock = LockService.getDocumentLock();
  lock.waitLock(30000);
  let backupUrl = '';
  try {
    const ss = SpreadsheetApp.getActiveSpreadsheet();
    ksP1AssertTarget_(ss);

    const data = ksP1LoadData_();
    ksP1ValidatePayload_(data);

    // Create a recoverable copy before any Phase 1 registry tab is written.
    const stamp = Utilities.formatDate(
      new Date(),
      Session.getScriptTimeZone() || 'Asia/Kolkata',
      'yyyyMMdd_HHmmss'
    );
    const backup = DriveApp.getFileById(ss.getId())
      .makeCopy(ss.getName() + '_BACKUP_BEFORE_PHASE1_' + stamp);
    backupUrl = backup.getUrl();

    const summaries = [];
    summaries.push(ksP1WriteOwnedTab_(ss, KS_P1.TABS.TABLES, data.tables));
    summaries.push(ksP1WriteOwnedTab_(ss, KS_P1.TABS.FIELDS, data.fields));
    summaries.push(ksP1WriteOwnedTab_(ss, KS_P1.TABS.CONTRACTS, data.contracts));
    summaries.push(ksP1WriteOwnedTab_(ss, KS_P1.TABS.RELATIONSHIPS, data.relationships));
    summaries.push(ksP1WriteIdPolicy_(ss));

    const logRows = [
      ['event_id', 'event_datetime', 'version', 'event', 'result', 'details', 'backup_url', 'source_export'],
      [
        Utilities.getUuid(),
        new Date(),
        KS_P1.VERSION,
        'PHASE1_FOUNDATION_INSTALLED',
        'SUCCESS',
        'Installed governance registers only. Business tabs and transaction data were not changed.',
        backupUrl,
        data.sourceWorkbook
      ],
      [
        Utilities.getUuid(),
        new Date(),
        KS_P1.VERSION,
        'SOURCE_COUNTS',
        'VERIFIED',
        'Tables=' + data.tables.length +
          '; Fields=' + data.fields.length +
          '; Backend contract fields=' + data.contracts.length +
          '; Relationship proposals=' + data.relationships.length,
        backupUrl,
        data.sourceWorkbook
      ]
    ];
    ksP1WriteRawTab_(ss, KS_P1.TABS.LOG, logRows);

    SpreadsheetApp.flush();

    const msg = [
      'Phase 1 foundation installed.',
      'Tables: ' + data.tables.length,
      'Fields: ' + data.fields.length,
      'Backend contract fields: ' + data.contracts.length,
      'Relationship proposals: ' + data.relationships.length,
      'Backup: ' + backupUrl,
      'Business records changed: NO'
    ].join('\n');

    // Log the completion details so the function also works when run from
    // the Apps Script editor, where spreadsheet UI access is unavailable.
    Logger.log(msg);
    return { success: true, backupUrl: backupUrl, tabs: summaries, message: msg };
  } catch (err) {
    throw new Error('Phase 1 installation stopped safely: ' + (err && err.message ? err.message : err));
  } finally {
    lock.releaseLock();
  }
}

function ksP1ShowSummary() {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const expected = [
    KS_P1.TABS.TABLES, KS_P1.TABS.FIELDS, KS_P1.TABS.CONTRACTS,
    KS_P1.TABS.RELATIONSHIPS, KS_P1.TABS.ID_POLICY, KS_P1.TABS.LOG
  ];
  const lines = expected.map(function(name) {
    const sh = ss.getSheetByName(name);
    return name + ': ' + (sh ? Math.max(0, sh.getLastRow() - 1) + ' records' : 'not installed');
  });
  const summary = lines.join('\n');
  Logger.log(summary);
  return summary;
}

function ksP1AssertTarget_(ss) {
  if (!ss) throw new Error('Open the target Google Sheet before running this function.');
  if (ss.getId() !== KS_P1.EXPECTED_SPREADSHEET_ID) {
    throw new Error(
      'Wrong spreadsheet. Expected ID ' + KS_P1.EXPECTED_SPREADSHEET_ID +
      ' but found ' + ss.getId() + '. No changes were made.'
    );
  }
  if (ss.getName().indexOf(KS_P1.EXPECTED_NAME_PREFIX) !== 0) {
    throw new Error('Unexpected spreadsheet name: ' + ss.getName() + '. No changes were made.');
  }
}

function ksP1LoadData_() {
  const compressed = Utilities.newBlob(
    Utilities.base64Decode(KS_P1_DATA_B64),
    'application/gzip',
    'ks_phase1_metadata.json.gz'
  );
  const jsonText = Utilities.ungzip(compressed).getDataAsString('UTF-8');
  return JSON.parse(jsonText);
}

function ksP1ValidatePayload_(data) {
  const checks = [
    ['tables', 218],
    ['fields', 3074],
    ['contracts', 888],
    ['relationships', 41]
  ];
  checks.forEach(function(item) {
    if (!data[item[0]] || data[item[0]].length !== item[1]) {
      throw new Error('Embedded ' + item[0] + ' count mismatch. Expected ' + item[1] + '.');
    }
  });
  if (!data.sourceWorkbook) throw new Error('Source workbook identity is missing.');
}

function ksP1WriteOwnedTab_(ss, tabName, records) {
  const headers = Object.keys(records[0] || {});
  if (!headers.length) throw new Error('No headers found for ' + tabName);

  const rows = [headers];
  records.forEach(function(record) {
    rows.push(headers.map(function(header) {
      const value = record[header];
      return value === null || value === undefined ? '' : value;
    }));
  });
  ksP1WriteRawTab_(ss, tabName, rows);
  return { tab: tabName, records: records.length };
}

