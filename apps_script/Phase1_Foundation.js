function ksP1WriteRawTab_(ss, tabName, rows) {
  let sh = ss.getSheetByName(tabName);
  if (!sh) sh = ss.insertSheet(tabName);

  // Only the six KS_P1-owned tabs are written by this script.
  // Existing business/operational tabs are never passed to this function.
  sh.clearContents();
  const width = Math.max.apply(null, rows.map(function(row) { return row.length; }));
  const normalized = rows.map(function(row) {
    const copy = row.slice();
    while (copy.length < width) copy.push('');
    return copy;
  });

  const chunkSize = 500;
  for (let start = 0; start < normalized.length; start += chunkSize) {
    const chunk = normalized.slice(start, start + chunkSize);
    sh.getRange(start + 1, 1, chunk.length, width).setValues(chunk);
  }

  sh.setFrozenRows(1);
  sh.getRange(1, 1, 1, width).setFontWeight('bold');
  sh.getRange(1, 1, sh.getMaxRows(), width).setWrap(false);
  sh.autoResizeColumns(1, Math.min(width, 12));
  return sh;
}
